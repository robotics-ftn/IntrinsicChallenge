#!/usr/bin/env python3
"""Intrinsic calibration of the RealSense D415 RGB sensor with a ChArUco board, set up the
same way as the main pose script: same serial / stream mode / frame grabbing / preview, and
the result goes to camera_data.json, which is where the main script reads K from
(USE_RS_INTRINSICS = False).

SPACE = capture a frame, Q = finish and calibrate, ESC = abort.

Two models are fitted to the same captures:
  pinhole - distortion fixed to 0. This K is written to camera_data.json, because the main
            script gives MegaPose the raw image and K only (nothing is undistorted there).
  full    - K + 5 distortion coefficients. Saved to the .npz under the same keys as before
            (camera_matrix, dist_coeffs), for code that passes dist to OpenCV (hand-eye).
"""

# Previous results (full model, 1920x1080):
# 950122060411  D415 LEFT   RMS 0.229 px
#   K    fx 1373.308  fy 1373.729  cx 948.567  cy 541.044
#   dist [ 1.43718478e-01 -4.00098985e-01 -2.99015090e-04  1.32550754e-03  2.75161111e-01]
#   factory  fx 1380.387  fy 1377.354  cx 940.339  cy 541.352   dist 0
# 950122061749  D415 RIGHT  RMS 0.214 px
#   K    fx 1363.244  fy 1364.016  cx 942.796  cy 540.649
#   dist [ 0.14495374 -0.40680407  0.00042401 -0.00243459  0.27733717]
#   factory  fx 1375.198  fy 1372.474  cx 950.192  cy 540.515   dist 0

import json
import os
import shutil
import time
from pathlib import Path

import cv2
import numpy as np
import pyrealsense2 as rs

# ---- same as the main script ----
# Project folder (one level above tools/); camera_data.json is written to <project>/config/
PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAMERA_SERIAL = "950122061749"
FRAME_WIDTH, FRAME_HEIGHT, FRAME_FPS = 1920, 1080, 8
FRAME_TIMEOUT_MS = 5000
WARMUP_FRAMES, FLUSH_GRABS = 5, 2
PREVIEW_SCALE = 0.5

# ---- board (must match the printed board) ----
SQUARES_X, SQUARES_Y = 7, 10
SQUARE_LENGTH, MARKER_LENGTH = 0.0245, 0.0185   # metres
DICTIONARY = cv2.aruco.DICT_5X5_100
# Boards with an even row count generated by OpenCV < 4.6 (or "legacy" generators) use a
# different layout. If markers are detected but no corners turn green, flip this.
LEGACY_PATTERN = False

MIN_CAPTURES, MIN_CHARUCO_CORNERS = 20, 6
# False when calibrating a camera the main script does not use (only the .npz is written).
WRITE_CAMERA_DATA = True

PINHOLE_FLAGS = (cv2.CALIB_ZERO_TANGENT_DIST | cv2.CALIB_FIX_K1
                 | cv2.CALIB_FIX_K2 | cv2.CALIB_FIX_K3)

board = cv2.aruco.CharucoBoard((SQUARES_X, SQUARES_Y), SQUARE_LENGTH, MARKER_LENGTH,
                               cv2.aruco.getPredefinedDictionary(DICTIONARY))
board.setLegacyPattern(LEGACY_PATTERN)
charuco_detector = cv2.aruco.CharucoDetector(board)


def start_camera():
    """Colour-only start, as in the main script (USE_DEPTH = False). Returns (pipe, profile)."""
    pipe, cfg = rs.pipeline(), rs.config()
    cfg.enable_device(CAMERA_SERIAL)
    cfg.enable_stream(rs.stream.color, FRAME_WIDTH, FRAME_HEIGHT, rs.format.bgr8, FRAME_FPS)
    try:
        profile = pipe.start(cfg)
    except RuntimeError as e:
        found = [d.get_info(rs.camera_info.serial_number) for d in rs.context().query_devices()]
        raise RuntimeError(f"Could not start RealSense {CAMERA_SERIAL} at {FRAME_WIDTH}x"
                           f"{FRAME_HEIGHT}@{FRAME_FPS} (connected: {found}): {e}")
    for _ in range(WARMUP_FRAMES):
        pipe.wait_for_frames(FRAME_TIMEOUT_MS)
    return pipe, profile


def read_frame(pipe):
    """Latest BGR frame, or None."""
    for _ in range(FLUSH_GRABS):
        pipe.poll_for_frames()
    try:
        frames = pipe.wait_for_frames(FRAME_TIMEOUT_MS)
    except RuntimeError:
        return None
    color = frames.get_color_frame()
    if not color:
        return None
    return np.asanyarray(color.get_data()).copy()   # copy: the SDK recycles the buffer


def detect(gray):
    corners, ids, marker_corners, marker_ids = charuco_detector.detectBoard(gray)
    # OpenCV 5 returns corners as (N, 2); drawing/matching expect (N, 1, 2).
    if corners is not None and ids is not None:
        corners = corners.reshape(-1, 1, 2).astype(np.float32)
        ids = ids.reshape(-1, 1).astype(np.int32)
    visible = ids is not None and len(ids) >= MIN_CHARUCO_CORNERS
    return visible, corners, ids, marker_corners, marker_ids


def calibrate(all_obj, all_img, flags=0):
    """(rms, K, dist, per-view RMS) for the captured views."""
    rms, K, dist, rvecs, tvecs = cv2.calibrateCamera(
        all_obj, all_img, (FRAME_WIDTH, FRAME_HEIGHT), None, None, flags=flags)
    per_view = []
    for obj, img, rvec, tvec in zip(all_obj, all_img, rvecs, tvecs):
        proj, _ = cv2.projectPoints(obj, rvec, tvec, K, dist)
        per_view.append(np.sqrt(np.mean(np.sum((proj.reshape(-1, 2) - img.reshape(-1, 2)) ** 2,
                                               axis=1))))
    return rms, K, dist.ravel(), per_view


def fmt_K(K):
    return f"fx {K[0, 0]:.3f}  fy {K[1, 1]:.3f}  cx {K[0, 2]:.3f}  cy {K[1, 2]:.3f}"


if __name__ == "__main__":
    pipe, profile = start_camera()
    dev = profile.get_device()
    print(f"{dev.get_info(rs.camera_info.name)} S/N {CAMERA_SERIAL} "
          f"USB {dev.get_info(rs.camera_info.usb_type_descriptor)}: "
          f"colour {FRAME_WIDTH}x{FRAME_HEIGHT}@{FRAME_FPS}")
    fi = profile.get_stream(rs.stream.color).as_video_stream_profile().get_intrinsics()
    factory_K = np.array([[fi.fx, 0, fi.ppx], [0, fi.fy, fi.ppy], [0, 0, 1]], dtype=np.float64)
    factory_dist = np.array(fi.coeffs, dtype=np.float64)

    all_obj, all_img = [], []
    try:
        while True:
            frame = read_frame(pipe)
            if frame is None:
                continue
            gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
            visible, corners, ids, marker_corners, marker_ids = detect(gray)

            view = frame.copy()
            if marker_ids is not None and len(marker_ids) > 0:
                cv2.aruco.drawDetectedMarkers(view, marker_corners, marker_ids)
            if visible:
                cv2.aruco.drawDetectedCornersCharuco(view, corners, ids)
            view = cv2.resize(view, None, fx=PREVIEW_SCALE, fy=PREVIEW_SCALE,
                              interpolation=cv2.INTER_AREA)
            cv2.putText(view, f"captured {len(all_obj)}/{MIN_CAPTURES}  corners "
                              f"{0 if ids is None else len(ids)}  SPACE=capture  Q=calibrate",
                        (12, 32), cv2.FONT_HERSHEY_SIMPLEX, 0.7,
                        (0, 255, 0) if visible else (0, 0, 255), 2, cv2.LINE_AA)
            cv2.imshow("calibration", view)
            key = cv2.waitKey(1) & 0xFF

            if key == ord(" ") and visible:
                obj, img = board.matchImagePoints(corners, ids)
                if obj is None or len(obj) < MIN_CHARUCO_CORNERS:
                    print("Not enough matched points, try again")
                    continue
                all_obj.append(obj.reshape(-1, 1, 3).astype(np.float32))
                all_img.append(img.reshape(-1, 1, 2).astype(np.float32))
                print(f"Captured frame {len(all_obj)} ({len(ids)} corners)")
            elif key == ord("q"):
                if len(all_obj) >= MIN_CAPTURES:
                    break
                print(f"Need at least {MIN_CAPTURES} captures, have {len(all_obj)}")
            elif key == 27:
                raise SystemExit("Aborted, nothing saved.")
    finally:
        pipe.stop()
        cv2.destroyAllWindows()

    rms_p, K_p, _, pv_p = calibrate(all_obj, all_img, PINHOLE_FLAGS)
    rms_f, K_f, dist_f, pv_f = calibrate(all_obj, all_img)
    worst = lambda pv: ", ".join(f"#{i + 1}={e:.2f}" for i, e in
                                 sorted(enumerate(pv), key=lambda x: -x[1])[:3])
    print(f"\npinhole (dist = 0)  RMS {rms_p:.3f} px   worst views {worst(pv_p)}")
    print(f"  {fmt_K(K_p)}")
    print(f"full (K + dist)     RMS {rms_f:.3f} px   worst views {worst(pv_f)}")
    print(f"  {fmt_K(K_f)}")
    print(f"  dist {dist_f}")
    print(f"factory ({fi.model})")
    print(f"  {fmt_K(factory_K)}")
    print(f"  dist {factory_dist}")
    # The pinhole RMS is the pixel error the main script lives with by ignoring distortion.
    # If it is far above the full RMS, undistort the frames there and use the full K instead.

    npz = os.path.join(PROJECT_DIR, "config", f"calibration_{CAMERA_SERIAL}.npz")
    np.savez(npz, camera_matrix=K_f, dist_coeffs=dist_f,
             camera_matrix_pinhole=K_p, rms=rms_f, rms_pinhole=rms_p,
             image_size=np.array((FRAME_WIDTH, FRAME_HEIGHT)),
             factory_camera_matrix=factory_K, factory_dist_coeffs=factory_dist)
    print(f"\nSaved both models to {npz}")

    if WRITE_CAMERA_DATA:
        path, data = Path(PROJECT_DIR) / "config" / "camera_data.json", {}
        if path.exists():
            backup = path.with_name(f"camera_data_{time.strftime('%Y%m%d_%H%M%S')}.json")
            shutil.copy(path, backup)
            data = json.loads(path.read_text())
            if "K" in data:
                print(f"old K   {fmt_K(np.array(data['K'], dtype=np.float64).reshape(3, 3))}"
                      f"   (backup: {backup.name})")
        data.update(K=K_p.tolist(), resolution=[FRAME_HEIGHT, FRAME_WIDTH])
        path.write_text(json.dumps(data, indent=2))
        print(f"new K   {fmt_K(K_p)}   -> {path}")